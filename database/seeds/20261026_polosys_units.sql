begin;
set local lock_timeout='8s';
lock table public."Polosys_units" in exclusive mode;

create temporary table requested_polosys_units (
  unit_code bigint primary key, name text unique not null, name_ar text not null
) on commit drop;
insert into requested_polosys_units values
  (1,'PCs','حبة'),
  (2,'Kg','كيلو'),
  (3,'Meter','متر'),
  (4,'Liter','لتر'),
  (5,'Ml','مل'),
  (6,'Bottle','عبوة'),
  (7,'Can','علبة'),
  (8,'Bag','كيس'),
  (9,'Dozen','دزينة'),
  (10,'Tray','طبق'),
  (11,'Packet','باكيت'),
  (12,'Packet-A','باكيت-A'),
  (13,'Packet-B','باكيت-B'),
  (14,'Packet-C','باكيت-C'),
  (15,'Packet-D','باكيت-D'),
  (16,'Packet-E','باكيت-E'),
  (17,'Packet-F','باكيت-F'),
  (18,'Packet-G','باكيت-G'),
  (19,'Packet-H','باكيت-H'),
  (20,'Ctn','كرتون'),
  (21,'Ctn-A','كرتون-A'),
  (22,'Ctn-B','كرتون-B'),
  (23,'Ctn-C','كرتون-C'),
  (24,'Ctn-D','كرتون-D'),
  (25,'Temporary Unit','وحدة مؤقتة');

do $$
begin
  if exists(select 1 from public."Polosys_units" u where not exists(select 1 from requested_polosys_units r where r.name=u.name)) then
    raise exception 'Unexpected existing unit names; seed cancelled for review';
  end if;
end; $$;

-- Keep the Temporary Unit UUID used by every staged product.
-- Permit the requested explicit code assignment only within this locked seed.
alter table public."Polosys_units" alter column unit_code set generated by default;
update public."Polosys_units" set unit_code=25,name_ar='وحدة مؤقتة'
  where name='Temporary Unit';

insert into public."Polosys_units" (unit_code,name,name_ar)
  overriding system value
  select unit_code,name,name_ar from requested_polosys_units order by unit_code
  on conflict(name) do update
    set unit_code=excluded.unit_code,name_ar=excluded.name_ar;

do $$
begin
  if (select count(*) from public."Polosys_units")<>25 or exists(
    select 1 from requested_polosys_units r left join public."Polosys_units" u
      on u.name=r.name and u.unit_code=r.unit_code and u.name_ar=r.name_ar
      where u.id is null
  ) then raise exception 'Unit list verification failed'; end if;
end; $$;
alter table public."Polosys_units" alter column unit_code set generated always;
select setval(pg_get_serial_sequence('public."Polosys_units"','unit_code'),25,true);
commit;
